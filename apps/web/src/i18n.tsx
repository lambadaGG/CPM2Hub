export type TKey = keyof (typeof translations)['en'];

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string }>({
  lang: 'en',
  setLang: () => {},
  t: (k) => k,
});

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('gm-lang') as Lang | null;
    if (saved && ['ru', 'en', 'id', 'ms', 'tr'].includes(saved)) return saved;
    const code = initDataUser()?.language_code ?? '';
    if (code.startsWith('ru')) return 'ru';
    if (code === 'id') return 'id';
    if (code === 'ms') return 'ms';
    if (code === 'tr') return 'tr';
    return 'en';
  } catch {
    return 'en';
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);

  useEffect(() => {
    try {
      localStorage.setItem('gm-lang', lang);
    } catch {
      /* ignore */
    }
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang: (l: Lang) => setLangState(l),
      t: (k: TKey) => translations[lang][k] ?? translations.en[k] ?? k,
    }),
    [lang],
  );

  return <LangCtx.Provider value={value}>{children}</LangCtx.Provider>;
}

export function useI18n() {
  return useContext(LangCtx);
}
